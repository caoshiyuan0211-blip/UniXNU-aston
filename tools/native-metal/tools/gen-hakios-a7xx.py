#!/usr/bin/env python3
"""gen-hakios-a7xx.py MESA_BUILD_REGS_DIR MAGIC.txt OUT.hpp INSTR_CACHE_SIZE -- hakios-metal's a7xx register header for the Adreno 740.

Copies, verbatim (Mesa is MIT), the definitions of the a7xx-only registers the a7xx compute and draw paths write, from the
a6xx.xml.h Mesa's build generates (enum parameters as uint32_t, so it stands next to hakios's a6xx.hpp), and the A740's
"magic" registers (Mesa freedreno_devices.py, a6xx.magic_raw of chip 0x43050a01), dumped by gen-a740-fill --magic.
"""
import re, sys
regs_dir, magic_txt, out, instr_cache = sys.argv[1], sys.argv[2], sys.argv[3], int(sys.argv[4])
src = open(f'{regs_dir}/a6xx.xml.h').read().split('\n')
pm4 = open(f'{regs_dir}/adreno_pm4.xml.h').read()
NAMES = ['HLSQ_INVALIDATE_CMD', 'HLSQ_CS_CNTL', 'HLSQ_FS_CNTL_0', 'HLSQ_CONTROL_2_REG', 'HLSQ_CONTROL_3_REG', 'HLSQ_CONTROL_4_REG',
         'HLSQ_CONTROL_5_REG', 'HLSQ_CS_CNTL_1', 'SP_CS_CNTL_1', 'HLSQ_CS_NDRANGE_0', 'HLSQ_CS_NDRANGE_1', 'HLSQ_CS_NDRANGE_2',
         'HLSQ_CS_NDRANGE_3', 'HLSQ_CS_NDRANGE_4', 'HLSQ_CS_NDRANGE_5', 'HLSQ_CS_NDRANGE_6', 'HLSQ_CS_LAST_LOCAL_SIZE',
         'HLSQ_CS_KERNEL_GROUP_X', 'HLSQ_CS_KERNEL_GROUP_Y', 'HLSQ_CS_KERNEL_GROUP_Z']
keep, i, found = [], 0, set()
def mine(name):
    for n in NAMES:
        if name == f'REG_A7XX_{n}' or name.startswith(f'A7XX_{n}_') and not any(name.startswith(f'A7XX_{m}_') for m in NAMES if len(m) > len(n) and m.startswith(n)):
            return n
while i < len(src):
    line = src[i]
    m = re.match(r'#define (\w+)', line) or re.match(r'static inline uint32_t (\w+)\(', line)
    n = mine(m.group(1)) if m else None
    if n:
        found.add(n)
        if line.startswith('static inline'):
            body = [re.sub(r'\(enum \w+ val\)', '(uint32_t val)', line)]
            i += 1
            while not src[i].startswith('}'):
                body.append(src[i]); i += 1
            body.append(src[i])
            keep += body
        else:
            keep.append(line)
    i += 1
missing = set(NAMES) - found
assert not missing, missing
# packet fields a7xx changed (adreno_pm4.xml.h), verbatim
PM4 = ['CP_EVENT_WRITE7_0_', 'CP_THREAD_CONTROL_0_']
pm4lines, j, p4 = [], 0, pm4.split('\n')
while j < len(p4):
    line = p4[j]
    m = re.match(r'#define (\w+)', line) or re.match(r'static inline uint32_t (\w+)\(', line)
    if m and any(m.group(1).startswith(x) for x in PM4):
        if line.startswith('static inline'):
            pm4lines.append(re.sub(r'\(enum \w+ val\)', '(uint32_t val)', line)); j += 1
            while not p4[j].startswith('}'): pm4lines.append(p4[j]); j += 1
            pm4lines.append(p4[j])
        else:
            pm4lines.append(line)
    j += 1
assert any('CP_EVENT_WRITE7_0_WRITE_ENABLED' in l for l in pm4lines) and any('CP_THREAD_CONTROL_0_THREAD' in l for l in pm4lines)
def enum(name):
    return int(re.search(rf'\b{name} = (\d+),', pm4).group(1))
magic = [tuple(int(x, 0) for x in l.split()) for l in open(magic_txt) if l.strip()]
with open(out, 'w') as f:
    f.write('// GENERATED by 12r/metal/tools/gen-hakios-a7xx.py from Mesa 25.0.7 (MIT): the a7xx-only registers hakios-metal writes on\n'
            '// the Adreno 740 (chip 0x43050a01, OnePlus 12R), verbatim from the a6xx.xml.h Mesa\'s build generates, and the A740\'s\n'
            '// magic registers from freedreno_devices.py. Do not edit.\n#pragma once\n#include <cassert>\n#include <cstdint>\n\nnamespace hakios::metal::a7xx {\n\n')
    f.write(f'constexpr uint32_t kChipId = 0x43050a01u;\n')
    f.write(f'constexpr uint32_t kInstrCacheSize = {instr_cache};   // freedreno_devices.py a6xx.instr_cache_size of the A740\n')
    for e in ('CACHE_FLUSH7', 'CACHE_INVALIDATE7', 'CP_THREAD_CONTROL', 'CP_SET_THREAD_BR', 'EV_WRITE_USER_32B', 'RB_DONE_TS', 'CP_EVENT_WRITE7', 'CCU_CLEAN_COLOR', 'CCU_CLEAN_DEPTH', 'CACHE_INVALIDATE', 'CACHE_FLUSH_TS', 'PC_CCU_FLUSH_COLOR_TS', 'PC_CCU_FLUSH_DEPTH_TS', 'WRITE_GE', 'CP_WAIT_REG_MEM', 'POLL_MEMORY'):
        f.write(f'constexpr uint32_t k{e.title().replace("_", "")} = {enum(e)};   // adreno_pm4.xml.h {e}\n')
    a6 = open(f'{regs_dir}/a6xx.xml.h').read()
    for e in ('WORKITEMRASTORDER_LINEAR', 'WORKITEMRASTORDER_TILED'):
        v = int(re.search(r'\b' + e + r' = (\d+),', a6).group(1))
        f.write('constexpr uint32_t k%s = %d;   // a6xx.xml.h %s\n' % (e.title().replace('_', ''), v, e))
    f.write('struct Magic { uint32_t reg, value; };\n')
    f.write('constexpr Magic kMagic[] = {' + ', '.join(f'{{0x{r:05x}, 0x{v:08x}}}' for r, v in magic) + '};\n\n')
    f.write('\n'.join(l.replace('static inline', 'static inline constexpr') for l in keep + pm4lines))
    f.write('\n\n}  // namespace hakios::metal::a7xx\n')
print(f'{out}: {len(keep)} lines, {len(found)} registers, {len(magic)} magic registers')
